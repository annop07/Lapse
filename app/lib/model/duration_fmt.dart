/// การจัดรูปเวลา — หน่วยของทั้งแอปคือ "วินาที"
///
/// เดิมสเปก §2.3 กำหนดหน่วยเป็นนาทีและทิ้ง session ที่สั้นกว่าหนึ่งนาที
/// เจ้าของผลิตภัณฑ์เปลี่ยนเป็นวินาทีหลังลองใช้จริง เหตุผลที่ให้ทิ้งของเดิม
/// คือ 30 วินาทีปัดเป็น 0 อยู่แล้วจึงไม่มีความหมาย พอนับวินาทีได้
/// เหตุผลนั้นก็หมดไป ตอนนี้จึงนับทุกวินาทีและไม่ทิ้งอะไรเลย
library;

/// `6443` → `1:47:23` · ใช้ทั้งในไฟล์ `[h:mm:ss]` และบนหน้าจอ
///
/// ชั่วโมงไม่เติมศูนย์ข้างหน้า นาทีกับวินาทีเติมเสมอ
String formatHms(int seconds) {
  final s = seconds < 0 ? 0 : seconds;
  final m = s ~/ 60;
  return '${m ~/ 60}:'
      '${(m % 60).toString().padLeft(2, '0')}:'
      '${(s % 60).toString().padLeft(2, '0')}';
}

/// `9645` → `2 ชั่วโมง 40 นาที` · ใช้ในแผงรายละเอียดของกำแพง
///
/// ระดับวันไม่ต้องละเอียดถึงวินาที เพราะกำแพงแบ่งระดับเป็นชั่วโมงอยู่แล้ว
String formatThai(int seconds) {
  final total = seconds < 0 ? 0 : seconds;
  if (total < 60) return '$total วินาที';

  final m = total ~/ 60;
  final h = m ~/ 60;
  final rest = m % 60;
  if (h == 0) return '$rest นาที';
  if (rest == 0) return '$h ชั่วโมง';
  return '$h ชั่วโมง $rest นาที';
}
