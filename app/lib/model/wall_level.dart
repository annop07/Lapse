/// ระดับของช่องบนกำแพง — 5 ขั้น โทนเดียว ไม่มีสี (§2.7)
library;

/// จำนวนวินาทีของวันหนึ่ง → ระดับ 0–4 ที่ใช้เลือกโทเคน `--lp-wall-N`
///
/// ขอบยังเป็นนาทีเหมือนเดิมตามสเปก แม้หน่วยที่เก็บจะเปลี่ยนเป็นวินาทีแล้ว
/// เพราะระดับของกำแพงพูดถึง "วันนั้นอ่านเยอะแค่ไหน" ไม่ใช่ความละเอียดของเวลา
///
/// | ระดับ | นาที    |
/// |-------|---------|
/// | 0     | 0       |
/// | 1     | 1–59    |
/// | 2     | 60–149  |
/// | 3     | 150–259 |
/// | 4     | 260+    |
int wallLevel(int seconds) {
  if (seconds <= 0) return 0;
  final minutes = seconds ~/ 60;
  if (minutes < 60) return 1;
  if (minutes < 150) return 2;
  if (minutes < 260) return 3;
  return 4;
}
