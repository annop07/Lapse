/// ระดับของช่องบนกำแพง — 5 ขั้น โทนเดียว ไม่มีสี (§2.7)
library;

/// จำนวนนาทีของวันหนึ่ง → ระดับ 0–4 ที่ใช้เลือกโทเคน `--lp-wall-N`
///
/// | ระดับ | นาที    |
/// |-------|---------|
/// | 0     | 0       |
/// | 1     | 1–59    |
/// | 2     | 60–149  |
/// | 3     | 150–259 |
/// | 4     | 260+    |
int wallLevel(int minutes) {
  if (minutes <= 0) return 0;
  if (minutes < 60) return 1;
  if (minutes < 150) return 2;
  if (minutes < 260) return 3;
  return 4;
}
